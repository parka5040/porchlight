#!/usr/bin/env python3
"""Verify the committed Cc/Cf/Zl/Zp table; regenerate only with its recorded UCD.
The fingerprint validates the pinned table even when Python ships a different UCD.
An intentional Unicode upgrade updates the version and fingerprint together.
"""
from hashlib import sha256
from pathlib import Path
import re
import sys
import unicodedata

RECORDED_VERSION = "16.0.0"
RECORDED_SHA256 = "f3eae481da19d020d5101a04b649650c7c0d3fad1df8331bc2fb28594a74e121"
PATH = Path(__file__).resolve().parent.parent / "server/api/src/blobs/filename_categories.rs"


def verify_committed(content):
    version = re.search(r"; Unicode ([0-9.]+)\.\n", content)
    assert version and version.group(1) == RECORDED_VERSION, "Recorded Unicode version differs"
    assert sha256(content.encode()).hexdigest() == RECORDED_SHA256, "Committed filename table differs"
    return version.group(1)


def generate_content(version):
    assert unicodedata.unidata_version == version, f"Regenerate with Unicode {version}"
    ranges = []
    for codepoint in range(0x110000):
        if unicodedata.category(chr(codepoint)) not in {"Cc", "Cf", "Zl", "Zp"}:
            continue
        if ranges and codepoint == ranges[-1][1] + 1:
            ranges[-1] = (ranges[-1][0], codepoint)
        else:
            ranges.append((codepoint, codepoint))
    pattern = "\n        | ".join(f"0x{start:x}" if start == end else f"0x{start:x}..=0x{end:x}" for start, end in ranges)
    return f'''// Generated by scripts/generate-filename-categories.py; Unicode {version}.
// General_Category Cc (control), Cf (format), Zl (line), Zp (paragraph).
// Do not edit character ranges by hand.
pub(super) fn excluded_filename_category(c: char) -> bool {{
    matches!(c as u32,
        {pattern}
    )
}}
'''


def main():
    if "--check" in sys.argv:
        content = PATH.read_text()
        version = verify_committed(content)
        if unicodedata.unidata_version != version:
            print(f"SKIP (python unicodedata {unicodedata.unidata_version} ≠ recorded {version})")
            return
        assert content == generate_content(version), "Regenerate filename categories"
        print(f"Filename General_Category filter is current (Unicode {version})")
    else:
        content = generate_content(RECORDED_VERSION)
        verify_committed(content)
        PATH.write_text(content)
        print(f"Generated filename General_Category filter (Unicode {RECORDED_VERSION})")


if __name__ == "__main__":
    main()
