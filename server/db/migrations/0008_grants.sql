SET LOCAL ROLE porchlight_owner;
SET LOCAL search_path = porchlight, pg_catalog;

-- porchlight_app. Domain rows are soft-deleted, revoked or expired, never deleted by the app (purges run as
-- porchlight_maintenance).
GRANT SELECT, INSERT, UPDATE ON
    households, users, user_credentials, household_members, devices, api_tokens, member_settings, items
    TO porchlight_app;
-- Certificate history is immutable (see the immutable_history trigger).
GRANT SELECT, INSERT ON device_certificates TO porchlight_app;
-- DELETE where rows expire (nightly purge of sessions and one-time tokens) or are generated by derivation.
GRANT SELECT, INSERT, UPDATE, DELETE ON
    sessions, enrollment_tokens, password_resets, item_occurrences, member_agenda, scheduled_reminders,
    item_derivation
    TO porchlight_app;
-- Relationship rows are immutable: no UPDATE.
GRANT SELECT, INSERT, DELETE ON item_assignees, item_viewers, item_reminders TO porchlight_app;
-- Append-only logs are written by SECURITY DEFINER triggers only.
GRANT SELECT ON item_revisions, task_events TO porchlight_app;
GRANT SELECT ON outbox TO porchlight_app;
GRANT UPDATE (stream_seq) ON outbox TO porchlight_app;
GRANT USAGE ON SEQUENCE outbox_stream_seq TO porchlight_app;
-- Row lock on the assignment mutex (SELECT ... FOR UPDATE needs both); agents get nothing.
GRANT SELECT, UPDATE ON stream_assign_mutex TO porchlight_app;

-- porchlight_agent: reads.
GRANT SELECT ON
    households, users, household_members, member_settings, items, item_assignees, item_viewers, item_reminders,
    item_occurrences, member_agenda, scheduled_reminders, item_derivation, item_revisions, task_events
    TO porchlight_agent;
-- Agent writes: authoritative inputs only.
GRANT INSERT, UPDATE ON items, member_settings TO porchlight_agent;
GRANT INSERT, DELETE ON item_assignees, item_viewers, item_reminders TO porchlight_agent;
GRANT UPDATE (status, board_position, completed_by, completed_at,
              override_local_start, override_local_end, override_local_due, override_due_date)
    ON item_occurrences TO porchlight_agent;

-- Note: btree_gist's functions are owned by the bootstrap superuser (trusted extension) and keep PUBLIC EXECUTE;
-- they are harmless internal/pure functions.
REVOKE EXECUTE ON ALL FUNCTIONS IN SCHEMA porchlight FROM PUBLIC;
GRANT EXECUTE ON FUNCTION pl_valid_tzid(text), pl_current_actor() TO porchlight_app, porchlight_agent;
DO $$ BEGIN EXECUTE format('REVOKE TEMPORARY ON DATABASE %I FROM PUBLIC', current_database()); END $$;
-- Functions created by later migrations must not default to PUBLIC EXECUTE either.
ALTER DEFAULT PRIVILEGES FOR ROLE porchlight_owner REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;

RESET search_path;
RESET ROLE;

GRANT SELECT ON public._sqlx_migrations TO porchlight_app;
